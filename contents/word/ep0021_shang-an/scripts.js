/* ---- shared render helpers ---- */
function escHtml(s) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}
function brJoin(s) {
  return escHtml(s).split('\n').join('<br>');
}
// narration inner HTML for a card under a style
function narrHtml(cardId, style) {
  const d = NARR[style][cardId];
  if (!d) return '';
  let html = '';
  if (d.s) html += '<strong>' + escHtml(d.s) + '</strong>';
  if (d.t) html += (html ? '<br>' : '') + brJoin(d.t);
  if (d.n) html += '<div class="note">' + brJoin(d.n) + '</div>';
  return html;
}
// plain text (for copy button)
function narrText(cardId, style) {
  const d = NARR[style][cardId];
  if (!d) return '';
  const parts = [];
  if (d.s) parts.push(d.s);
  if (d.t) parts.push(d.t);
  if (d.n) parts.push(d.n);
  return parts.join('\n');
}
